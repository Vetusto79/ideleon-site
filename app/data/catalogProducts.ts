export type CatalogFieldOption = {
  label: string;
  value?: string;
};

export type CatalogRequestField = {
  id: string;
  label: string;
  type: "select" | "text";
  options?: CatalogFieldOption[];
  defaultValue?: string;
  placeholder?: string;
  inputMode?: "text" | "numeric" | "decimal";
  unit?: string;
  condition?: { fieldId: string; equals: string };
};

export type CatalogCalculatorLink = {
  label: string;
  title: string;
  text: string;
  href: string;
};

