const select = (id: string, label: string, values: string[], defaultValue?: string): CatalogRequestField => ({
  id,
  label,
  type: "select",
  defaultValue: defaultValue || values[0],
  options: values.map((value) => ({ label: value, value })),
});

const text = (
  id: string,
  label: string,
  placeholder: string,
  inputMode: "text" | "numeric" | "decimal" = "text",
  unit?: string,
): CatalogRequestField => ({ id, label, type: "text", placeholder, inputMode, unit });

